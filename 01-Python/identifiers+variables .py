# Identifiers and Variables in Python 

# Identifiers
# An identifier is a name given to a variable, function, class, or module in Python.
# It must start with a letter (a-z, A-Z) or an underscore (_), followed by letters, digits (0-9), or underscores.
# It is case-sensitive.

# Valid identifiers
my_variable = 10
_my_variable = 20
Variable1 = 30

# Invalid identifiers
# 1variable = 10  # Starts with a digit
# my-variable = 20  # Contains a hyphen
# my variable = 30  # Contains a space

# Variables
# A variable is a named location in memory that stores a value.
# In Python, you don't need to declare the type of a variable explicitly.

#example 1
name = 'abdi'
age = 20
height = 8.7

print(name)
print(age)
print(height)


# example 2
marks = 60
bones = 20 

total_marks =  marks+bones 
print(total_marks)

