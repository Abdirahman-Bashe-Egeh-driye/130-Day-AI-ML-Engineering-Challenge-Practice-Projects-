#A data type tells Python what kind of value a variable contains.
#Python has several built-in data types, including:
# 1. Integer (int): Whole numbers, e.g., 5, -10, 0
# 2. Float (float): Decimal numbers, e.g., 3.14, -2.5, 0.0
# 3. String (str): Text, e.g., "Hello", 'Python'
# 4. Boolean (bool): True or False values

#example 1
name = 'ABDI'
age = 20
height = 6.7
is_student = True
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))


